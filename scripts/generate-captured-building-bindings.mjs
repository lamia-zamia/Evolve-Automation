/** Preserve the retired automation catalog's ownership while adapters evolve. */
import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import ts from "typescript";

const retiredCatalogRef = "95ea7cc0^:src/game/entity-catalogs.ts";
const retiredCatalogSource = execFileSync("git", ["show", retiredCatalogRef], {
  encoding: "utf8",
});
const retiredCatalogSyntax = ts.createSourceFile(
  "entity-catalogs.ts",
  retiredCatalogSource,
  ts.ScriptTarget.Latest,
  true,
);
let retiredBuildingObject;
function findRetiredBuildingObject(node) {
  if (
    ts.isVariableDeclaration(node) &&
    node.name.getText(retiredCatalogSyntax) === "buildings"
  ) {
    retiredBuildingObject = node.initializer;
  }
  ts.forEachChild(node, findRetiredBuildingObject);
}
findRetiredBuildingObject(retiredCatalogSyntax);
if (
  !retiredBuildingObject ||
  !ts.isObjectLiteralExpression(retiredBuildingObject)
) {
  throw new Error("retired Building catalog missing");
}
const retiredBuildingBindings = retiredBuildingObject.properties.map(
  (property) => {
    if (
      !ts.isPropertyAssignment(property) ||
      !ts.isNewExpression(property.initializer)
    ) {
      throw new Error(
        `unexpected Building entry ${property.getText(retiredCatalogSyntax)}`,
      );
    }
    const args = property.initializer.arguments;
    const region = args?.[1];
    const id = args?.[2];
    if (
      !region ||
      !id ||
      !ts.isStringLiteral(region) ||
      !ts.isStringLiteral(id)
    ) {
      throw new Error(
        `nonliteral Building identity ${property.name.getText(retiredCatalogSyntax)}`,
      );
    }
    return `${region.text}-${id.text}`;
  },
);
const uniqueRetiredBuildingBindings = [
  ...new Set(retiredBuildingBindings),
].sort();
await writeFile(
  "src/adapters/evolve/progression/build/captured-building-bindings.generated.ts",
  `// Generated by scripts/generate-captured-building-bindings.mjs.\n// Ownership from ${retiredCatalogRef}; upstream registries do not define automation membership.\nexport const CAPTURED_AUTOMATION_BUILDING_BINDINGS: ReadonlySet<string> = new Set([\n${uniqueRetiredBuildingBindings.map((binding) => `  ${JSON.stringify(binding)},`).join("\n")}\n]);\n`,
);
process.stdout.write(
  `${uniqueRetiredBuildingBindings.length} automation Building bindings\n`,
);
