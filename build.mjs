import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import * as esbuild from "esbuild";
import { createBuildOptions } from "./build-config.mjs";

const root = path.dirname(fileURLToPath(import.meta.url));
const metadataPath = path.join(root, "src", "userscript.meta.js");
const local = process.argv.includes("--local");
const testSurface = process.argv.includes("--test-surface");
const researchConditionGate = process.argv.includes(
  "--research-condition-gate",
);
if (local && researchConditionGate) {
  throw new Error(
    "--local cannot be combined with --research-condition-gate; the pilot build targets the production game hosts",
  );
}
if (testSurface && !local) {
  throw new Error(
    "--test-surface requires --local and cannot target a production build",
  );
}
const outputDirectory = local
  ? path.join(root, "test-artifacts", "local")
  : researchConditionGate
    ? path.join(root, "test-artifacts", "research-condition-gate")
    : root;
const metadataOutputPath = path.join(
  outputDirectory,
  local ? "evolve_automation.local.meta.js" : "evolve_automation.meta.js",
);
const userscriptOutputPath = path.join(
  outputDirectory,
  local
    ? testSurface
      ? "evolve_automation.test-surface.user.js"
      : "evolve_automation.local.user.js"
    : "evolve_automation.user.js",
);
const watch = process.argv.includes("--watch");

// The released metadata block carries one @match per supported host. The local
// build serves a single origin, so every @match collapses into the localhost one.
function replaceFirstMatchWithLocalhost() {
  let replaced = false;
  return () => {
    if (replaced) {
      return "";
    }
    replaced = true;
    return "// @match        http://localhost:4400/*\n";
  };
}

const sourceMetadata = (await readFile(metadataPath, "utf8")).trimEnd();
const metadata = researchConditionGate
  ? sourceMetadata
      .replace(
        /^\/\/ @name\s+.*$/m,
        "// @name         Evolve Automation (Research Gate Pilot)",
      )
      .replace(
        /^\/\/ @namespace\s+.*$/m,
        "// @namespace    https://evolve-automation.local/research-gate-pilot",
      )
      .replace(/^\/\/ @downloadURL.*\r?\n/m, "")
      .replace(/^\/\/ @updateURL.*\r?\n/m, "")
  : local
    ? sourceMetadata
        .replace(
          /^\/\/ @name\s+.*$/m,
          "// @name         Evolve Automation (DeadSpace local)",
        )
        .replace(
          /^\/\/ @namespace\s+.*$/m,
          "// @namespace    http://localhost/evolve-automation",
        )
        .replace(/^\/\/ @downloadURL.*\r?\n/m, "")
        .replace(/^\/\/ @updateURL.*\r?\n/m, "")
        .replace(/^\/\/ @match.*\r?\n/gm, replaceFirstMatchWithLocalhost())
    : sourceMetadata;
if (
  !metadata.startsWith("// ==UserScript==") ||
  !metadata.endsWith("// ==/UserScript==")
) {
  throw new Error(
    `${metadataPath} is not a complete userscript metadata block`,
  );
}

await mkdir(outputDirectory, { recursive: true });

const buildOptions = createBuildOptions({
  root,
  outfile: userscriptOutputPath,
  banner: {
    js: `${metadata}\n\n// Generated by npm run build. Edit files under src/ instead.`,
  },
  researchConditionGate,
  testSurface,
});

if (watch) {
  await writeFile(metadataOutputPath, `${metadata}\n`, "utf8");
  const context = await esbuild.context(buildOptions);
  await context.watch();
  console.log("Watching src/**/*.{js,ts}; press Ctrl+C to stop.");
} else {
  await esbuild.build(buildOptions);
  await writeFile(metadataOutputPath, `${metadata}\n`, "utf8");
}
