const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const baselineRevision = "744e01a5f9a18d75ba87c36a1c59a0c85a7286cc";
const diagnosticSourcePath =
  "src/domain/civic/allocation-diagnostic-admission.ts";
const baselineFiles = [
  "src/adapters/evolve/civic/captured-ordinary-jobs.ts",
  "src/bootstrap/captured-runtime-control.ts",
];
const bundleDirectory = resolve(root, "test-artifacts/p50/bundles");
const bundlePaths = {
  before: resolve(bundleDirectory, "before/evolve_automation.user.js"),
  after: resolve(bundleDirectory, "after/evolve_automation.user.js"),
  testSurface: resolve(
    bundleDirectory,
    "test-surface-after/evolve_automation.test-surface.user.js",
  ),
};
const diagnosticFunctions = [
  "admitAllocationDiagnosticObservation",
  "observeTestAllocationDiagnosticRequest",
  "capturedOrdinaryAllocationDiagnosticFacts",
  "capturedAllocationDiagnosticFacts",
  "capturedJobsDecisionIdentity",
];
const counterNames = [
  "testControlResolutionCount",
  "testSettingsReadCount",
  "testCatalogReadCount",
  "testDemandReadCount",
  "testNativeRootReadCount",
];

const sha256 = (value) =>
  createHash("sha256").update(value).digest("hex").toUpperCase();

function metadataForBuild(local) {
  const source = readFileSync(resolve(root, "src/userscript.meta.js"), "utf8");
  if (!local) return source.trimEnd();
  let replacedMatch = false;
  return source
    .replace(
      /^\/\/ @name\s+.*$/m,
      "// @name         Evolve Automation (DeadSpace local)",
    )
    .replace(
      /^\/\/ @namespace\s+.*$/m,
      "// @namespace    http://localhost/evolve-automation",
    )
    .replace(/^\/\/ @downloadURL.*\r?\n/m, "")
    .replace(/^\/\/ @updateURL.*\r?\n/m, "")
    .replace(/^\/\/ @match.*\r?\n/gm, () => {
      if (replacedMatch) return "";
      replacedMatch = true;
      return "// @match        http://localhost:4400/*\n";
    })
    .trimEnd();
}

function buildBanner(local) {
  return `${metadataForBuild(local)}\n\n// Generated by npm run build. Edit files under src/ instead.`;
}

function sourceAtRevision(revision, relativePath) {
  return execFileSync("git", ["show", `${revision}:${relativePath}`], {
    cwd: root,
    encoding: "utf8",
  });
}

function baselineSourcePlugin() {
  const contentsByPath = new Map(
    baselineFiles.map((relativePath) => [
      resolve(root, relativePath),
      sourceAtRevision(baselineRevision, relativePath),
    ]),
  );
  return {
    name: "p50-baseline-source",
    setup(build) {
      build.onLoad({ filter: /\.ts$/ }, (args) => {
        const contents = contentsByPath.get(resolve(args.path));
        return contents === undefined ? null : { contents, loader: "ts" };
      });
    },
  };
}

async function compileBundle({ testSurface, baseline = false }) {
  const result = await esbuild.build({
    ...createBuildOptions({
      root,
      outfile: resolve(
        root,
        `test-artifacts/p50/builds/${baseline ? "before" : testSurface ? "test-surface" : "after"}.user.js`,
      ),
      banner: { js: buildBanner(testSurface) },
      testSurface,
      ...(baseline ? { plugins: [baselineSourcePlugin()] } : {}),
    }),
    write: false,
    metafile: true,
    logLevel: "silent",
  });
  return {
    code: result.outputFiles[0].text,
    metafile: result.metafile,
  };
}

function preserveBundle(path, code) {
  mkdirSync(dirname(path), { recursive: true });
  if (existsSync(path)) {
    assert.equal(
      readFileSync(path, "utf8"),
      code,
      `immutable P50 bundle changed: ${path}`,
    );
    return;
  }
  writeFileSync(path, code, { flag: "wx" });
}

function functionAncestorName(node) {
  if (
    ts.isFunctionDeclaration(node) ||
    ts.isFunctionExpression(node) ||
    ts.isArrowFunction(node) ||
    ts.isMethodDeclaration(node)
  )
    return node.name?.getText() ?? "anonymous";
  return undefined;
}

function hasIdentifier(rootNode, name) {
  let found = false;
  function visit(node) {
    if (ts.isIdentifier(node) && node.text === name) found = true;
    if (!found) ts.forEachChild(node, visit);
  }
  visit(rootNode);
  return found;
}

function isCounterIncrement(node, name) {
  let expression = node;
  while (ts.isParenthesizedExpression(expression))
    expression = expression.expression;
  return (
    ts.isBinaryExpression(expression) &&
    expression.operatorToken.kind === ts.SyntaxKind.PlusEqualsToken &&
    ts.isIdentifier(expression.left) &&
    expression.left.text === name
  );
}

function analyzeBundle(code, metafile) {
  const source = ts.createSourceFile(
    "compiled-user-script.js",
    code,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.JS,
  );
  const functions = {};
  const calls = {};
  const identifierCounts = {};
  const strings = new Set();
  let objectiveAndScopeBytes = 0;
  let testObservationIfConditions = 0;
  let testObservationConditionalExpressions = 0;
  let testObservationLogicalChecks = 0;
  const perCycleChecks = {
    ordinaryReadCycleGeneration: 0,
    ordinaryObservationGate: 0,
    fullJobsCatalogCounterGate: 0,
    fullJobsDemandCounterGate: 0,
  };

  function visit(node, functionAncestors = []) {
    const ancestorName = functionAncestorName(node);
    const nextAncestors =
      ancestorName === undefined
        ? functionAncestors
        : [ancestorName, ...functionAncestors];

    if (
      ts.isFunctionDeclaration(node) &&
      node.name !== undefined &&
      (diagnosticFunctions.includes(node.name.text) ||
        node.name.text === "createOrdinaryJobsTestInstrumentation" ||
        node.name.text === "createFullJobsTestInstrumentation")
    )
      functions[node.name.text] = Buffer.byteLength(
        code.slice(node.getStart(source), node.end),
      );

    if (ts.isCallExpression(node) && ts.isIdentifier(node.expression)) {
      const name = node.expression.text;
      calls[name] = (calls[name] ?? 0) + 1;
    }

    if (ts.isIdentifier(node))
      identifierCounts[node.text] = (identifierCounts[node.text] ?? 0) + 1;
    if (ts.isStringLiteralLike(node)) strings.add(node.text);

    if (
      ts.isVariableStatement(node) &&
      node.declarationList.declarations.some((declaration) =>
        [
          "FOOD_STONE_DIAGNOSTIC_OBJECTIVE",
          "FOOD_STONE_DIAGNOSTIC_SCOPE",
        ].includes(
          ts.isIdentifier(declaration.name) ? declaration.name.text : "",
        ),
      )
    )
      objectiveAndScopeBytes += Buffer.byteLength(
        code.slice(node.getStart(source), node.end),
      );

    if (
      ts.isIfStatement(node) &&
      hasIdentifier(node.expression, "testObservationEnabled")
    )
      testObservationIfConditions += 1;
    if (
      ts.isConditionalExpression(node) &&
      hasIdentifier(node.condition, "testObservationEnabled")
    ) {
      testObservationConditionalExpressions += 1;
      if (nextAncestors.includes("readCycle"))
        perCycleChecks.ordinaryReadCycleGeneration += 1;
    }
    if (
      ts.isBinaryExpression(node) &&
      [
        ts.SyntaxKind.AmpersandAmpersandToken,
        ts.SyntaxKind.BarBarToken,
      ].includes(node.operatorToken.kind) &&
      hasIdentifier(node.left, "testObservationEnabled")
    ) {
      testObservationLogicalChecks += 1;
      if (hasIdentifier(node.right, "observeTestAllocationDiagnosticRequest"))
        perCycleChecks.ordinaryObservationGate += 1;
      if (isCounterIncrement(node.right, "testCatalogReadCount"))
        perCycleChecks.fullJobsCatalogCounterGate += 1;
      if (isCounterIncrement(node.right, "testDemandReadCount"))
        perCycleChecks.fullJobsDemandCounterGate += 1;
    }
    ts.forEachChild(node, (child) => visit(child, nextAncestors));
  }
  visit(source);

  const outputMetadata = Object.values(metafile.outputs)[0];
  const admissionModuleBytes =
    Object.entries(outputMetadata.inputs).find(([inputPath]) =>
      inputPath.replaceAll("\\", "/").endsWith(diagnosticSourcePath),
    )?.[1].bytesInOutput ?? 0;
  const retainedDiagnosticFunctionBytes = diagnosticFunctions.reduce(
    (total, name) => total + (functions[name] ?? 0),
    0,
  );

  return {
    bytes: Buffer.byteLength(code),
    sha256: sha256(code),
    admissionModuleBytes,
    objectiveAndScopeBytes,
    functions,
    retainedDiagnosticFunctionBytes,
    calls: {
      admissionPredicate: calls.admitAllocationDiagnosticObservation ?? 0,
      ordinaryAndFullJobsObservers:
        calls.observeTestAllocationDiagnosticRequest ?? 0,
    },
    testObservationChecks: {
      ifConditions: testObservationIfConditions,
      conditionalExpressions: testObservationConditionalExpressions,
      logicalChecks: testObservationLogicalChecks,
      perCycle: perCycleChecks,
      perCycleTotal: Object.values(perCycleChecks).reduce(
        (total, count) => total + count,
        0,
      ),
    },
    retainedDiagnosticIdentifiers: Object.fromEntries(
      [
        "readTestAllocationDiagnosticRequest",
        "onTestAllocationDiagnosticAdmission",
        "testObservationEnabled",
        ...counterNames,
        "allocationDiagnosticAdmissionDependencies",
      ].map((name) => [name, identifierCounts[name] ?? 0]),
    ),
    markers: {
      objective: strings.has(
        "maintain-food-buffer-and-useful-stone-production",
      ),
      scope: strings.has("food-sustainability-and-useful-stone-replenishment"),
      eventKind: strings.has("p48-allocation-diagnostic-observation"),
      requestHook: strings.has("allocationDiagnosticRequest"),
      observerHook: strings.has("observeAllocationDiagnosticAdmission"),
      observationOnlyAuthority: strings.has("observation-only"),
      noExecutionAuthority: strings.has("none"),
    },
  };
}

export async function runBundleAudit() {
  const beforeBuild = await compileBundle({
    testSurface: false,
    baseline: true,
  });
  const afterBuild = await compileBundle({ testSurface: false });
  const testSurfaceBuild = await compileBundle({ testSurface: true });
  preserveBundle(bundlePaths.before, beforeBuild.code);
  preserveBundle(bundlePaths.after, afterBuild.code);
  preserveBundle(bundlePaths.testSurface, testSurfaceBuild.code);

  const before = analyzeBundle(beforeBuild.code, beforeBuild.metafile);
  const after = analyzeBundle(afterBuild.code, afterBuild.metafile);
  const testSurface = analyzeBundle(
    testSurfaceBuild.code,
    testSurfaceBuild.metafile,
  );

  assert.ok(before.admissionModuleBytes > 0);
  assert.equal(after.admissionModuleBytes, 0);
  assert.equal(after.calls.admissionPredicate, 0);
  assert.equal(after.calls.ordinaryAndFullJobsObservers, 0);
  assert.equal(after.retainedDiagnosticFunctionBytes, 0);
  assert.equal(after.testObservationChecks.perCycleTotal, 0);
  assert.deepEqual(
    diagnosticFunctions.filter(
      (name) => testSurface.functions[name] === undefined,
    ),
    [],
  );
  assert.equal(testSurface.calls.admissionPredicate, 1);
  assert.equal(testSurface.calls.ordinaryAndFullJobsObservers, 2);
  assert.ok(testSurface.admissionModuleBytes > 0);
  assert.equal(testSurface.markers.objective, true);
  assert.equal(testSurface.markers.scope, true);

  return {
    schema: "p50-diagnostic-bundle-audit-v1",
    baselineRevision,
    compiler: "esbuild with repository build-config.mjs options",
    outputModes: {
      ordinaryProduction: before,
      ordinaryProductionAfter: after,
      localTestSurfaceAfter: testSurface,
    },
    sizeDeltaBytes: after.bytes - before.bytes,
    sourceMaps: "not emitted; build options do not enable sourcemaps",
    immutableBundles: Object.fromEntries(
      Object.entries(bundlePaths).map(([name, path]) => [
        name,
        {
          path: path.replaceAll("\\", "/"),
          sha256: sha256(readFileSync(path)),
        },
      ]),
    ),
  };
}

if (
  process.argv[1] !== undefined &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  console.log(JSON.stringify(await runBundleAudit(), null, 2));
}
